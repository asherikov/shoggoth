class PrUpdateCommand(CommandBase):
    # Slash command regex: a comment whose body is exactly
    # ``/command_name`` — no leading/trailing whitespace, no other
    # content. The ``\w+`` class excludes slashes / spaces so a
    # ``/command extra`` comment falls through to the normal
    # ``_pr_comment`` review-comments flow. ``action == "created"``
    # is enforced in ``_detect_slash_command`` so edits / deletes
    # do not re-fire commands (only the original invocation does).
    SLASH_COMMAND_RE = re.compile(r"^/(\w+)$")

    # ``/do`` is the bare trigger: it carries no instructions
    # itself. Posting ``/do`` on a PR tells the agent to
    # re-read the PR's comment thread and execute the
    # instructions left there — even instructions that were
    # left by the slave user (which the regular review-
    # comments flow ignores via the trusted-user filter).
    # ``SLASH_DO_RE`` matches just the bare command word
    # (with optional trailing whitespace); any text after
    # ``/do`` falls through to the regular review-comments
    # path so ``/do something`` is treated as a normal
    # comment, not a trigger.
    SLASH_DO_RE = re.compile(r"^/do\s*$")

    # Catalog surfaced by ``/help``. Tuples keep the order stable
    # without making callers depend on Python's dict ordering
    # guarantee (the file targets Python 3).
    #
    # ``sandbox`` lives here (rather than alongside the
    # dispatcher-only ``command: sandbox`` entry) because the
    # help message is the user's only discoverability surface
    # for the per-PR sandbox spawner. The handler itself
    # never reaches this file — ``gitea-pr-sandbox-binding``'s
    # selector pins ``comment.body == "/sandbox"`` and submits
    # the ``command-handler`` DAG with
    # ``command: sandbox``, which routes through
    # ``DispatchCommand._handle_sandbox`` (in
    # ``shoggoth/workflow/scripts/shoggoth/commands/dispatch.py``)
    # and skips the worker step entirely. The catalog entry
    # therefore describes the dispatcher's behaviour, not
    # this worker's, so a user who runs ``/sandbox`` on the
    # pr-update path (a route the pr-update binding's
    # drop-list already filters out) would see the spawner
    # feature surface in /help but its invocation would be
    # silently no-op'd — see ``_handle_slash_command`` for the
    # silent-no-op design.
    SUPPORTED_COMMANDS = (
        ("help", "List available slash commands"),
        ("review", "Request a code review from the slave user "
                   "(identical to assigning a review request)"),
        ("squash", "Squash all commits in this PR into a single "
                   "commit; the commit message is generated by an "
                   "agent from the cumulative diff"),
        ("rebase", "Rebase this PR on top of the target branch; "
                   "conflicts are resolved by an agent"),
        ("do", "Re-read the PR's comment thread and execute the "
               "instructions left there. The trigger must be a "
               "reply to a specific inline review comment."),
        # ``/sandbox`` is NOT handled here — it's a sibling-
        # binding dispatch (gitea-pr-sandbox-binding) that
        # routes through ``DispatchCommand._handle_sandbox``
        # in shoggoth/workflow/scripts/shoggoth/commands/dispatch.py
        # and skips the worker step. The catalog entry is here
        # for /help discoverability only; the pr-update
        # binding's drop-list (gitea-pr-update-binding.yaml)
        # already filters /sandbox comments so this entry
        # never reaches ``_handle_slash_command`` from the
        # Gitea side. If a user lands here via a non-Gitea
        # path, the silent-no-op design (see
        # ``_handle_slash_command``) treats the unknown
        # command as "no handler" and returns.
        ("sandbox", "Spawn a per-PR sandbox pod (ttyd terminal "
                    "exposed at /sandbox/<id>/) with the PR's "
                    "branch already cloned. Routed via the "
                    "gitea-pr-sandbox binding; from the "
                    "pr-update path this is a no-op. Pod "
                    "auto-destroys when the terminal session "
                    "closes; multiple sandboxes can run "
                    "concurrently"),
    )

    def __init__(self, shoggoth, gitea, redmine, agent):
        super().__init__(gitea, redmine, agent, shoggoth=shoggoth)

    def execute(self):
        action = self.gitea.get_pr_action()
        log(f"pr-update: action={action}")
        if action in ("review_request_removed", "synchronize"):
            return

        pr_url = self.gitea.get_pr_url()
        pr_number = self.gitea.get_pr_number()
        log(f"pr-update: pr_url={pr_url}")

        if action == "deleted":
            # DEFENCE IN DEPTH: the gitea-pr-update binding's
            # selector already drops
            # ``payload.action == "deleted"`` events before
            # the workflow pod is even applied (see
            # gitea-pr-update-binding.yaml:138), so this
            # branch is unreachable on the Gitea-side
            # path. The distinctive log line ("DEFENCE IN
            # DEPTH") makes any future selector relaxation
            # surface immediately in the Argo log: a
            # workflow that runs this branch was supposed
            # to be filtered, and the operator's first
            # action should be to re-tighten the binding.
            # The log line is also the load-bearing audit
            # trail if ``_pr_comment`` ever throws on a
            # non-Gitea code path (Redmine updates, etc.)
            # — the operator can grep for it in the
            # workflow log.
            print(f"=== DEFENCE IN DEPTH: PR COMMENT CHECK "
                  f"AFTER COMMENT DELETION: pr={pr_url} "
                  f"repo={self.shoggoth.working_repo} ===",
                  flush=True)
            self._pr_comment(pr_number, pr_url)
            return

        if self.gitea.has_review():
            if self.gitea.is_review_by_slave_user():
                log("pr-update: review is by slave user, skipping")
            else:
                print(f"=== PR COMMENT ADDRESSING: pr={pr_url} "
                      f"repo={self.shoggoth.working_repo} ===", flush=True)
                self._pr_comment(self.gitea.get_pr_number(), pr_url)
        elif action == "review_requested" and self.gitea.is_slave_user_reviewer():
            # Gitea fires ``review_requested`` for both the
            # first request and any re-request, so the
            # ``is_slave_user_reviewer`` test alone is not
            # enough: a re-request after the slave already
            # submitted a review on the same head would
            # cause the slave to re-run the same review
            # over again. The state-based guard below
            # looks up the slave's existing review rows
            # on the current head SHA and skips the
            # re-run when one of them is a submitted
            # state (``COMMENT`` / ``APPROVED`` /
            # ``REQUEST_CHANGES``). PENDING and
            # REQUEST_REVIEW rows do not count — a draft
            # or a fresh re-request placeholder still
            # leaves the door open. When the head SHA
            # changes (a push), the previous submission's
            # ``commit_id`` no longer matches and the
            # slave will re-review the new commit.
            head_sha = (self.gitea._payload
                        .get("pull_request", {})
                        .get("head", {})
                        .get("sha", ""))
            slave_user = params.shoggoth_slave_user
            if (head_sha and slave_user
                    and self.gitea.slave_has_submitted_review_on_head(
                        slave_user, head_sha)):
                log(f"pr-update: slave already submitted a review on "
                    f"head={head_sha}; skipping re-request")
                otlp = self.agent.otlp
                if otlp is not None:
                    otlp._push_line(
                        f"pr-update: slave already submitted a review on "
                        f"head={head_sha}; skipping re-request")
                return
            print(f"=== PR REVIEW: pr={pr_url} "
                  f"repo={self.shoggoth.working_repo} ===", flush=True)
            self._pr_review(pr_url)
        else:
            # Slash-command dispatch fires before the generic
            # review-comments walk so a comment whose body is just
            # ``/command_name`` is consumed by the command handler
            # instead of being treated as a (text-only) review
            # comment that has nothing to address.
            if action == "created":
                slash_command = self._detect_slash_command()
                if slash_command:
                    print(f"=== PR SLASH COMMAND: pr={pr_url} "
                          f"repo={self.shoggoth.working_repo} "
                          f"command=/{slash_command} ===", flush=True)
                    self._handle_slash_command(slash_command,
                                               pr_number, pr_url)
                    return
            print(f"=== PR COMMENT CHECK: pr={pr_url} "
                  f"repo={self.shoggoth.working_repo} ===", flush=True)
            self._pr_comment(self.gitea.get_pr_number(), pr_url)

    def _pr_review(self, pr_url):
        pr_repo = self.shoggoth.working_repo
        pr_number = self.gitea.get_pr_number()
        log(f"pr-review: repo={pr_repo} pr={pr_number}")

        pr_data = self.gitea.get_pr(pr_repo, pr_number)
        pr_title = pr_data.get("title", "") if pr_data else ""
        pr_base = pr_data.get("base", {}).get("ref", "") if pr_data else ""
        pr_sha = pr_data.get("head", {}).get("sha", "") if pr_data else ""

        self.agent.start_session("pr-review")
        otlp = self.agent.otlp
        otlp._push_line(
            f"pr-review: starting review pr={pr_number} repo={pr_repo} "
            f"title={pr_title!r} base={pr_base} head={pr_sha}")

        review_repo_dir = self.shoggoth._resolve_review_repo_dir(pr_repo, pr_number)
        otlp._push_line(f"pr-review: resolved review_repo_dir={review_repo_dir}")

        self.shoggoth._unshallow(review_repo_dir)
        otlp._push_line(f"pr-review: _unshallow done for {review_repo_dir}")

        self.shoggoth._ensure_remote_ref(review_repo_dir, pr_base, pr_number)
        otlp._push_line(f"pr-review: _ensure_remote_ref base={pr_base} done")

        if pr_sha:
            self.shoggoth._ensure_remote_ref(review_repo_dir, pr_sha, pr_number)
            otlp._push_line(f"pr-review: _ensure_remote_ref head={pr_sha} done")

        diff_path = f"/tmp/shoggoth-pr-{pr_number}-{uuid.uuid4().hex[:8]}.diff"
        wrote = self.shoggoth._write_pr_diff(review_repo_dir, pr_base, pr_sha, diff_path)
        diff_size = os.path.getsize(diff_path) if os.path.exists(diff_path) else 0
        if not wrote:
            gitea_diff = self.gitea.get_pr_diff_text(pr_repo, pr_number)
            if gitea_diff:
                with open(diff_path, "w", encoding="utf-8") as f:
                    f.write(gitea_diff)
                diff_size = len(gitea_diff)
                log(f"pr-review: using Gitea-rendered diff "
                    f"({diff_size} bytes)")
                otlp._push_line(
                    f"pr-review: Gitea .diff fallback wrote {diff_size} bytes")
            else:
                log("pr-review: Gitea .diff fallback also empty")
                otlp._push_line("pr-review: Gitea .diff fallback empty")
        else:
            otlp._push_line(
                f"pr-review: _write_pr_diff wrote {diff_size} bytes "
                f"to {diff_path}")
        # ``_format_review_json`` only consults ``diff_text is not None``
        # to decide whether to render inline-comment placeholders in
        # the body and emit a parallel ``inline_comments`` list; the
        # actual content of the diff is never inspected. Pass a
        # sentinel rather than reading the file's contents into
        # memory (a multi-MB diff would otherwise be held in the
        # Python process through to the end of ``_pr_review`` for
        # no functional reason). ``None`` triggers the body-only
        # path; any non-``None`` value triggers the inline path.
        inline_comments_enabled = True if diff_size > 0 else None

        wt_path, diff_source = self.shoggoth._apply_pr_to_worktree(
            self.shoggoth.repo_dir, pr_base, pr_sha,
            review_repo_dir, pr_number)
        if wt_path is None:
            otlp.last_error = "could not create review worktree with PR diff applied"
            self.agent.stop_session()
            die(f"pr-review: failed to set up review worktree")
        otlp._push_line(
            f"pr-review: worktree ready at {wt_path} "
            f"(diff_source={diff_source})")

        try:
            review_prompt = (
                f"You are reviewing PR {pr_url} (repo: {pr_repo}, "
                f"PR #{pr_number}).\n"
                f"Title: {pr_title}\n"
                f"Base: {pr_base}\n"
                f"Head SHA: {pr_sha}\n\n"
                f"The PR has been applied as UNCOMMITTED changes to a "
                f"git worktree at: {wt_path}\n"
                f"This is the source tree you must review. Read files from "
                f"this path; do NOT read from any other checkout.\n\n"
                f"The unified diff is also preserved at: {diff_path} "
                f"({diff_size} bytes) for line-number references.\n\n"
                f"To inspect the change:\n"
                f"  - `git -C {wt_path} status` to see modified files\n"
                f"  - `git -C {wt_path} diff` to see the full diff against "
                f"the base\n"
                f"  - read the modified files directly to understand "
                f"context, callers, and existing patterns\n\n"
                f"You may use the codebase-memory MCP tools "
                f"(search_graph, get_code_snippet, trace_path) for context "
                f"lookups; the indexed code path is "
                f"{self.shoggoth.repo_dir}, so cross-reference by reading "
                f"matching files from the worktree path.\n"
                f"Use basic_memory MCP (search, read_note) for prior "
                f"project decisions.\n\n"
                f"Produce a code review focused on:\n"
                f"- correctness (logic bugs, off-by-one, edge cases)\n"
                f"- security (input validation, secrets in code, race "
                f"conditions)\n"
                f"- maintainability (clarity, naming, coupling)\n"
                f"- test coverage gaps (does the change add or modify code "
                f"without tests?)\n"
                f"- adherence to project conventions (look at neighbouring "
                f"code in the same files)\n\n"
                f"Do NOT make code changes. Do NOT post comments or reviews "
                f"via Gitea MCP tools — only the workflow script posts the "
                f"final review.\n\n"
                f"When done, output a single JSON object inside a ```json "
                f"fenced block, followed by the literal line END_OF_REVIEW "
                f"on its own line. The JSON shape is:\n"
                f"```\n"
                f"{{\n"
                f'  "verdict": "approve" | "request_changes" | "comment",\n'
                f'  "summary": "one-paragraph summary of the change",\n'
                f'  "findings": [\n'
                f"    {{\n"
                f'      "severity": "critical" | "high" | "medium" | '
                f'"low" | "info",\n'
                f'      "path": "relative/path/to/file (relative to the '
                f'worktree)",\n'
                f'      "line": 42,\n'
                f'      "body": "description of the issue and concrete '
                f"fix\"\n"
                f"    }}\n"
                f"  ]\n"
                f"}}\n"
                f"```\n\n"
                f"If the change is sound and small, output verdict "
                f'"approve" with an empty findings list. If you find any '
                f"critical or high-severity issue, output verdict "
                f'"request_changes".\n\n'
                f"Important: do not skip the END_OF_REVIEW line — it tells "
                f"the workflow script your review is complete."
            )

            log(f"pr-review: invoking agent prompt "
                f"(diff_source={diff_source}, diff={diff_size} bytes)")
            otlp._push_line(
                f"pr-review: invoking agent prompt "
                f"(diff_source={diff_source} diff_size={diff_size} "
                f"prompt_chars={len(review_prompt)})")

            t0 = time.time()
            rc = self.agent.prompt_with_retry(review_prompt,
                                              timeout=Agent.AGENT_TIMEOUT,
                                              cwd=wt_path,
                                              retry_label="pr-review")
            elapsed = time.time() - t0

            otlp._push_line(
                f"pr-review: agent prompt finished rc={rc} "
                f"elapsed={elapsed:.1f}s "
                f"assistant_chars="
                f"{sum(len(t) for t in otlp.assistant_text)}")

            if rc == 124:
                self._handle_timeout(pr_repo, pr_number, pr_url, [])
                return
            if rc != 0:
                otlp.last_error = f"agent prompt exited with code {rc}"
                otlp._push_line(
                    f"pr-review: ERROR agent prompt exited with code {rc} "
                    f"last_error={otlp.last_error}")
                self.agent.stop_session()
                die(f"pr-review: agent exited with code {rc}")

            review_text = otlp.get_review_text()
            otlp.last_result = review_text
            otlp._push_line(
                f"pr-review: extracted review_text length={len(review_text)}")

            review_data = self.agent._extract_review_json(review_text)
            inline_comments = []
            if review_data is not None:
                review_md, inline_comments = self.agent._format_review_json(
                    review_data, pr_title, pr_url,
                    diff_text=inline_comments_enabled)
                otlp._push_line(
                    f"pr-review: parsed JSON review "
                    f"verdict={review_data.get('verdict', '?')!r} "
                    f"findings="
                    f"{len(review_data.get('findings') or [])} "
                    f"inline_comments={len(inline_comments)}")
            else:
                otlp._push_line(
                    "pr-review: no JSON block found in agent output; "
                    "posting raw assistant text as Markdown")
                review_md = review_text.strip() if review_text else ""

            if not review_md:
                log("pr-review: no review text captured from agent")
                otlp._push_line(
                    "pr-review: no review text captured from agent")
                self.agent.stop_session()
                return

            log(f"pr-review: posting review to gitea "
                f"(length={len(review_md)}, inline_comments="
                f"{len(inline_comments)})")
            otlp._push_line(
                f"pr-review: posting review to gitea "
                f"(length={len(review_md)}, inline_comments="
                f"{len(inline_comments)})")
            if inline_comments and pr_sha:
                result = self.gitea.post_pr_review_with_inline(
                    pr_repo, pr_number, review_md, "COMMENT",
                    inline_comments, pr_sha)
                if result is None:
                    log("pr-review: inline review post failed; "
                        "falling back to body-only review")
                    otlp._push_line(
                        "pr-review: inline review post failed; "
                        "falling back to body-only review")
                    # ``review_md`` was rendered with the inline
                    # flag (``inline_comments_enabled is True``),
                    # so each finding's body became a placeholder
                    # (``see inline comment``) and the full text
                    # lives only in the inline-comment payload
                    # Gitea rejected. Regenerate the body without
                    # the flag so the placeholders become full
                    # text — the fallback must carry the finding
                    # text, not the placeholder.
                    if review_data is not None:
                        review_md = self.agent._format_review_json(
                            review_data, pr_title, pr_url)
                    result = self.gitea.post_pr_review_chunked(
                        pr_repo, pr_number, review_md)
                elif isinstance(result, dict):
                    # Review posted with inline comments.
                    # Post a follow-up issue comment with
                    # a clickable index of the inline
                    # comments — the review body has
                    # "see inline comment" placeholders
                    # (Gitea doesn't expose per-comment
                    # URLs in the POST response and doesn't
                    # support editing a posted review body),
                    # so the follow-up provides the actual
                    # links. Best-effort: if the fetch
                    # fails, the inline comments are still
                    # posted; only the follow-up links are
                    # missing.
                    review_id = result.get("id")
                    if review_id:
                        # ``pull_request_url`` from the
                        # POST response is the canonical
                        # PR URL Gitea uses internally —
                        # use it as the base for
                        # constructing per-comment URLs
                        # (format:
                        # ``{pull_request_url}#issuecomment-{id}``).
                        # Avoids reconstructing the URL
                        # from ``pr_repo``/``pr_number``
                        # (which could differ in trailing
                        # slash, query params, etc.) and
                        # guarantees the ``#issuecomment-``
                        # fragment resolves to the right
                        # comment.
                        pr_url = result.get(
                            "pull_request_url", "")
                        self._post_review_followup_with_links(
                            pr_repo, pr_number, pr_url,
                            review_id, review_data,
                            inline_comments, otlp)
            else:
                # ``pr_sha`` is empty (or ``inline_comments``
                # empty), so the inline post was skipped — but the
                # ``review_md`` was already rendered with the
                # inline flag set, so any finding that did have a
                # path/line is a placeholder whose full text lives
                # only in the inline-comment payload that will
                # never go anywhere. Regenerate without the flag so
                # the body carries full text.
                if review_data is not None:
                    review_md = self.agent._format_review_json(
                        review_data, pr_title, pr_url)
                result = self.gitea.post_pr_review_chunked(
                    pr_repo, pr_number, review_md)
            if result is None:
                otlp.last_error = "failed to post review to gitea"
                self.agent.stop_session()
                die("pr-review: failed to post review to gitea")
            otlp._push_line("pr-review: review posted to gitea")
        finally:
            log(f"pr-review: removing review worktree {wt_path}")
            self.shoggoth._remove_review_worktree(wt_path)
            otlp._push_line(f"pr-review: removed worktree {wt_path}")

        otlp._push_line(
            f"pr-review: session done elapsed={time.time() - t0:.1f}s "
            f"review_chars={len(review_md)}")
        self.agent.stop_session()

    def _post_review_followup_with_links(self, pr_repo, pr_number,
                                           pr_url, review_id,
                                           review_data, inline_comments,
                                           otlp):
        """Post a follow-up issue comment with a clickable
        index of the inline comments posted in the review.

        The review body has "see inline comment"
        placeholders (Gitea doesn't expose per-comment
        URLs in the POST review response and doesn't
        support editing a posted review body), so the
        follow-up provides the actual links. Reviewers
        see the inline comments at the right lines AND
        a navigable index in the PR conversation.

        Best-effort: if the comments fetch fails, the
        inline comments are still posted (they're already
        in Gitea by the time this runs) — only the
        follow-up links are missing. The function logs
        a warning and returns; the workflow continues.

        ``pr_url`` is ``pull_request_url`` from the
        POST review response — the canonical PR URL
        Gitea uses internally. Used as the base for
        constructing per-comment URLs in the format
        ``{pr_url}#issuecomment-{id}`` (the same format
        Gitea itself uses in
        ``services/convert/pull_review.go`` via
        ``comment.HTMLURL(ctx)``). Constructing the URL
        from the canonical base (rather than
        reconstructing it from ``pr_repo``/``pr_number``
        or using ``html_url`` from the GET response)
        guarantees the fragment resolves to the right
        comment even if the PR URL formatting differs
        (trailing slash, query params, etc.).

        ``review_data`` is the parsed review JSON
        (verdict, summary, findings); used to render the
        follow-up header. ``inline_comments`` is the
        list of inline comments we sent in the review
        (each ``{path, new_position, body}``); used to
        build the index. The per-comment ``id`` is
        fetched from Gitea by matching on ``(path, line)``.
        """
        try:
            comments = self.gitea.get_pr_review_comments(
                pr_repo, pr_number, review_id)
        except Exception as e:
            log(f"pr-review: WARNING failed to fetch "
                f"review comments for follow-up: {e}",
                file=sys.stderr)
            otlp._push_line(
                f"pr-review: WARNING failed to fetch "
                f"review comments for follow-up: {e}")
            return
        if not comments:
            log(f"pr-review: WARNING no comments returned "
                f"for review {review_id}; skipping follow-up",
                file=sys.stderr)
            otlp._push_line(
                f"pr-review: WARNING no comments returned "
                f"for review {review_id}; skipping follow-up")
            return
        # Build a map of (normalised_path, line) ->
        # comment_id from the Gitea response. The
        # response uses ``position`` (= ``LineNum``
        # internally, the file line number) and
        # ``path`` exactly as we sent them. The URL
        # is then constructed as
        # ``{pr_url}#issuecomment-{id}`` below —
        # using the canonical ``pr_url`` from the
        # POST response guarantees the fragment
        # resolves to the right comment.
        # Normalise the path the same way
        # ``Agent._format_review_json`` normalises the
        # path key it stashes on each inline comment,
        # so the lookup matches the agent's normalised
        # form even when Gitea returns the comment
        # with a prefix (``./README.md``,
        # ``/README.md``) the agent never reported.
        id_map = {}
        for c in comments:
            path = _normalise_diff_path(c.get("path", ""))
            line = c.get("position", 0)
            cid = c.get("id", 0)
            if path and line and cid:
                id_map[(path, line)] = cid
        # Build the follow-up body. The verdict and
        # summary go in the header; the inline-comment
        # index goes under a sub-heading. The full text
        # of each finding is NOT duplicated here — it
        # lives in the inline comments themselves (per
        # the "no duplication" requirement).
        rd = review_data or {}
        verdict = rd.get("verdict") or ""
        summary = (rd.get("summary")
                   or rd.get("summary_md")
                   or rd.get("body") or "")
        parts = ["## Code review summary", ""]
        if verdict:
            parts.append(f"**Verdict:** {verdict}")
            parts.append("")
        if summary:
            parts.append(summary.strip())
            parts.append("")
        parts.append("### Inline comments")
        parts.append("")
        parts.append("Click a link to jump to the comment:")
        parts.append("")
        for ic in inline_comments:
            path = ic.get("path", "?")
            line = ic.get("new_position", 0)
            cid = id_map.get((path, line), 0)
            label = f"`{path}:{line}`"
            if cid and pr_url:
                url = f"{pr_url}#issuecomment-{cid}"
                parts.append(f"- [{label}]({url})")
            else:
                # No comment ID matched (the GET
                # response didn't include this path/
                # line) or no ``pr_url`` from the POST
                # response — fall back to plain text
                # so the line is still listed.
                parts.append(f"- {label}")
        followup_body = "\n".join(parts)
        otlp._push_line(
            f"pr-review: posting follow-up summary with "
            f"{len(inline_comments)} inline comment link(s)")
        result = self.gitea.post_pr_comment(
            pr_repo, pr_number, followup_body)
        if result is None:
            log(f"pr-review: WARNING failed to post "
                f"follow-up summary comment",
                file=sys.stderr)
            otlp._push_line(
                "pr-review: WARNING failed to post "
                "follow-up summary comment")
        else:
            otlp._push_line(
                "pr-review: follow-up summary posted")

    def _resolve_task(self, branch):
        issues = self.redmine.list_issues(self.shoggoth.project)
        if issues is None:
            return None
        if "/" not in branch:
            return None
        parts = branch.split("/", 1)
        branch_subject = normalize_for_branch(parts[1])
        for issue in issues:
            if normalize_for_branch(issue.get("subject", "")) == branch_subject:
                return issue.get("id")
        return None

    def _pr_comment(self, pr_number, pr_url):
        pr_repo = self.shoggoth.working_repo
        pr_branch = self.shoggoth.working_branch
        task_subject = self.shoggoth.task_subject
        log(f"pr-comment: repo={pr_repo} pr={pr_number} branch={pr_branch}")

        unresolved = self.gitea.get_unresolved_review_comments(pr_repo, pr_number)
        log(f"pr-comment: unresolved comments={len(unresolved) if unresolved else 0}")

        if not unresolved:
            print("No unresolved review comments")
            return

        resolved_comments = []
        deferred_resolves = []
        redmine_task_id = None
        redmine_note = None
        changes_produced = False

        self.agent.start_session("pr-comment")

        try:
            rc = self.agent.prompt_with_retry(
                f"Load memories regarding the project {self.shoggoth.project} from basic memory. "
                f"Proceed if memory is not available.",
                retry_label="pr-comment-mem-project")
            if rc != 0:
                die(f"qwen agent exited with code {rc}")

            if task_subject:
                rc = self.agent.prompt_with_retry(
                    f"Load memories regarding task \"{task_subject}\" "
                    f"in project {self.shoggoth.project} from basic memory. "
                    f"Proceed if memory is not available.", resume=True,
                    retry_label="pr-comment-mem-task")
                if rc != 0:
                    die(f"qwen agent exited with code {rc}")

            for comment in unresolved:
                c_path = comment.get("path", "unknown")
                c_line = comment.get("line")
                c_body = comment.get("body", "")
                comment_id = comment.get("id")
                if not c_body:
                    if comment_id is not None:
                        deferred_resolves.append(comment_id)
                    resolved_comments.append(comment)
                    continue
                location = f"{c_path}:{c_line}" if c_line is not None else c_path
                prompt = (
                    f"Address the following review comment on PR {pr_url} "
                    f"(file: {location}): "
                    f"{c_body}. Use the codebase-memory skill to understand "
                    f"the code context around the comment. "
                    f"Leave all changes uncommitted in the working tree. "
                    f"Do not post comments, reviews, or replies via Gitea MCP tools."
                )
                rc = self.agent.prompt_with_retry(prompt, resume=True,
                                                  timeout=Agent.AGENT_TIMEOUT,
                                                  retry_label="pr-comment")
                if rc == 124:
                    self._handle_timeout(pr_repo, pr_number, pr_url, resolved_comments)
                if rc != 0:
                    die(f"qwen agent exited with code {rc}")

                summary = self.agent.otlp.get_review_text().strip()
                summary_lines = summary.split("\n") if summary else []
                body_first_line = c_body.split("\n")[0].strip()
                commit_subject = body_first_line[:72]
                comment_link = f"{pr_url}#issuecomment-{comment_id}" if comment_id is not None else pr_url
                run_url = params.shoggoth_argo_run_url
                run_url_line = f"\nArgo run: {run_url}" if run_url else ""
                if summary_lines:
                    commit_body = summary[-1000:]
                    if len(summary) > 1000:
                        commit_body = "... (truncated)\n" + commit_body
                    commit_msg = f"{commit_subject}\n\n{comment_link}{run_url_line}\n\n{commit_body}"
                else:
                    commit_msg = f"{commit_subject}\n\n{comment_link}{run_url_line}"
                committed = self._commit_only(commit_msg)
                if committed:
                    resolved_comments.append(comment)
                    if comment_id is not None:
                        deferred_resolves.append(comment_id)

            rc = self.agent.prompt_with_retry(
                f"Finalize all remaining work. Update basic memory with any new information "
                f"learned about the project {self.shoggoth.project}.",
                resume=True, timeout=Agent.AGENT_TIMEOUT,
                retry_label="pr-comment-finalize")
            if rc == 124:
                self._handle_timeout(pr_repo, pr_number, pr_url, resolved_comments)
            if rc != 0:
                die(f"qwen agent exited with code {rc}")

            if task_subject:
                rc = self.agent.prompt_with_retry(
                    f"Update basic memory with any new information learned about "
                    f"the task \"{task_subject}\".", resume=True, timeout=Agent.AGENT_TIMEOUT,
                    retry_label="pr-comment-finalize-task")
                if rc == 124:
                    self._handle_timeout(pr_repo, pr_number, pr_url, resolved_comments)
                if rc != 0:
                    die(f"qwen agent exited with code {rc}")

            self.agent.stop_session()

            changes_produced = len(resolved_comments) > 0
            log(f"pr-comment: resolved_comments={len(resolved_comments)}")

            redmine_task_id = self._resolve_task(pr_branch)
            log(f"pr-comment: redmine_task_id={redmine_task_id} changes_produced={changes_produced}")
            if redmine_task_id:
                note = f"Review comments on {pr_url} have been addressed."
                run_url = params.shoggoth_argo_run_url
                if run_url:
                    note += f" Argo run: {run_url}."
                redmine_note = note
        finally:
            self._push_pending_commits()
            for comment_id in deferred_resolves:
                r = self.gitea.resolve_comment(pr_repo, comment_id)
                if r is None:
                    log(f"pr-comment: WARNING resolve failed for comment {comment_id}")
                else:
                    log(f"pr-comment: resolved comment {comment_id}")
            if redmine_task_id and redmine_note is not None:
                if changes_produced:
                    self.redmine.update_issue(redmine_task_id,
                         "--status", "Resolved",
                         "--note", redmine_note)
                else:
                    self.redmine.update_issue(redmine_task_id,
                         "--note", redmine_note)

    # ----- slash commands (workflow) ---------------------------------

    def _detect_slash_command(self):
        """Return the slash-command name (without the leading ``/``)
        if the current PR comment is a slash command, otherwise
        ``None``.

        Matches ``SLASH_COMMAND_RE`` against the stripped body of the
        ``comment`` field in the webhook payload. ``action ==
        "created"`` is enforced so an ``edited``/``deleted`` comment
        does not re-fire the command — only the original invocation
        counts, mirroring how GitHub slash-command bots typically
        gate on ``action == "created"``.

        The check is deliberately strict (``^/(\\w+)$``, no
        content besides the command name) per the spec:
        surrounding whitespace is stripped first (so an accidental
        newline before ``/help`` is still recognised) but anything
        after the command — e.g. ``/help please`` — falls through
        to ``_pr_comment`` as a normal PR comment.

        ``/do`` is matched by the separate ``SLASH_DO_RE`` first;
        it's a bare trigger (no trailing text), and the handler
        reads the comment thread rather than executing the
        command body itself. A ``/do something`` body does NOT
        match ``SLASH_DO_RE`` and falls through to the normal
        review-comments path as a regular comment.
        """
        if self.gitea.get_pr_action() != "created":
            return None
        body = self.gitea.get_pr_comment_body().strip()
        if self.SLASH_DO_RE.match(body):
            return "do"
        m = self.SLASH_COMMAND_RE.match(body)
        return m.group(1) if m else None

    def _handle_slash_command(self, command, pr_number, pr_url):
        """Dispatch ``/command`` to its handler.

        Looks up ``_slash_<command>`` on this class; unknown
        names silently no-op (a log line is recorded but no
        PR-visible response is posted). Users who want to
        discover what's supported post ``/help`` explicitly.
        Handler exceptions are caught, posted as a PR
        comment, and then the workflow ``die()``s so the
        failure is visible in the Argo log and the step is
        marked Failed — a slash command that half-ran
        (e.g. force-pushed a squashed branch but failed
        before reporting back) must not return success to
        the workflow template.
        """
        pr_repo = self.shoggoth.working_repo
        log(f"slash-command: command=/{command} repo={pr_repo} "
            f"pr={pr_number}")

        # Trust check: only ``shoggoth_trusted_users`` can
        # drive ANY slash command. Implemented here (rather
        # than in execute()) so any future dispatch path
        # also inherits the gate without having to
        # remember to add it. The check is silent on
        # rejection — posting a PR-visible "not
        # authorized" message would leak the existence of
        # the command names and give unauthenticated
        # users a probe channel. The Argo log line is
        # sufficient for the trusted user auditing what
        # happened.
        #
        # In particular the slave user (the agent's own
        # account) is NOT allowed to trigger slash
        # commands. The earlier design gave the slave
        # an exception for ``/do`` and ``/help`` (so it
        # could leave instructions in a review comment
        # and trigger a pass); the trust model has since
        # been tightened to require a trusted human in
        # the loop. ``/do`` is now reply-only — the
        # trusted human replies to a review comment with
        # ``/do`` to drive the agent on that thread —
        # so the slave's own comments inside the thread
        # still surface (they are part of the thread
        # body), but only the trusted human can press
        # the trigger.
        comment = self.gitea._payload.get("comment") or {}
        author = (comment.get("user") or {}).get("login") or ""
        trusted_users = set(
            (params.shoggoth_trusted_users or "").split(","))
        trusted_users.discard("")
        if not author or author not in trusted_users:
            log(f"slash-command: rejecting /{command} from "
                f"non-trusted user {author!r} "
                f"(allowed={sorted(trusted_users)})",
                file=sys.stderr)
            return

        handler = getattr(self, f"_slash_{command}", None)
        if handler is None:
            # INTENTIONAL DESIGN: silent no-op for unknown
            # slash commands. See the longer rationale at
            # the SUPPORTED_COMMANDS catalog entry for
            # ``sandbox`` (this same file): the pr-update
            # path does not handle ``/sandbox`` (it routes
            # via the sibling ``gitea-pr-sandbox-binding``,
            # not via a ``_slash_sandbox`` method here) and
            # posting a "Unknown command" PR comment surfaced
            # noise on every typo (including ones the user
            # wrote in a quoted code block in the
            # conversation, never meant as a command). The
            # documented contract: silence is the default;
            # users discover the supported set via ``/help``
            # explicitly. A future change could re-add the
            # noisy comment for the trust-gated case if the
            # signal-to-noise is judged worth it — the
            # current judgement is no.
            log(f"slash-command: no handler for /{command}; "
                f"silently no-op (no PR-visible response)")
            return
        # ``/do`` needs the inline ``(path, line)`` anchor for
        # the thread the user replied to. The webhook
        # payload's ``IssueCommentPayload.Comment`` struct
        # (Gitea ``modules/structs/issue_comment.go:11``) is
        # the stripped-down ``*api.Comment`` — it carries
        # only ``id`` (plus body, user, urls, timestamps);
        # ``path`` and ``position`` are NOT serialised
        # because replies to inline review comments are
        # dispatched through
        # ``notify_service.CreateIssueComment`` with
        # ``convert.ToAPIComment`` rather than through
        # ``PullRequestReview`` with
        # ``*api.PullReviewComment``. Reading ``comment.path``/
        # ``comment.position`` from the webhook always
        # returns ``None`` — see the inline comments on
        # ``Gitea.find_review_comment_by_id`` for the full
        # trace through the Gitea source.
        #
        # Recovery: take the reply's ``comment.id`` (which
        # IS the database id of the row created by
        # ``CreateCodeComment(..., replyReviewID=parent.ReviewID, ...\,
        # parent.Line, parent.TreePath, ...)``) and id-match
        # it against ``/reviews/{id}/comments``. The matched
        # row carries the same ``path``/``position`` as the
        # parent comment (the reply row inherits them from
        # the parent at creation time, see
        # ``services/pull/review.go:266``), which is exactly
        # the thread anchor ``get_pr_review_thread`` filters
        # on.
        #
        # When the lookup returns ``None`` — top-level PR
        # comments (``Type == CommentTypeComment``, which the
        # review-comments endpoint never surfaces), or
        # ``comment.id`` is absent on the payload, or the id
        # belongs to a deleted comment — both ``thread_path``
        # and ``thread_line`` stay ``None`` and the existing
        # gate inside ``_slash_do``
        # (``if thread_path is None or thread_line is None:
        # return``) silently drops the trigger. That matches
        # the original "no parent thread = no-op" policy and
        # closes the bug where the Webhook-only lookup
        # silently no-op'd on EVERY ``/do`` invocation
        # (including valid inline replies).
        thread_path = None
        thread_line = None
        if command == "do":
            comment_id = comment.get("id")
            if comment_id is not None:
                match = self.gitea.find_review_comment_by_id(
                    pr_repo, pr_number, comment_id)
                if match is not None:
                    thread_path = match.get("path")
                    thread_line = match.get("position")
        try:
            if command == "do":
                handler(pr_repo, pr_number, pr_url,
                        thread_path, thread_line)
            else:
                handler(pr_repo, pr_number, pr_url)
        except Exception as e:
            log(f"slash-command: command=/{command} failed: {e}",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Command `/{command}` failed: {e}")
            # Fail the workflow, not just the command. The PR
            # comment above gives the user a clean pointer to the
            # reason; dying surfaces the same reason in the Argo
            # log (which the workflow template displays prominently
            # and which Argo uses to mark the step as Failed) and
            # stops the rest of the dispatch path from running on
            # a half-completed state. The pre-fix behaviour
            # (silently continue) hid the very bugs the user is
            # trying to debug — e.g. the ``session_id = None``
            # crash in /squash, where the workflow succeeded in
            # Argo despite the command being a no-op.
            die(f"slash-command: /{command} failed: {e}")

    def _post_slash_response(self, pr_repo, pr_number, body,
                              fatal=False, command=None):
        """Post a slash-command response as an issue-style comment.

        Used by every ``_slash_*`` handler to confirm success or
        explain failure. A ``None`` return from ``post_pr_comment``
        is logged but does not raise — the original command may
        already have made destructive changes (e.g. force-push on
        ``/squash``) and the workflow should not abort at that
        point on a comment-post failure alone.

        When ``fatal=True`` the caller is reporting a failure that
        the workflow must not return success on (a soft failure
        path: handler caught the error, posted a comment, returned
        without raising). After posting, this calls ``die()`` so
        the Argo step is marked Failed and the user sees the same
        message in the workflow log; ``command`` names the slash
        command for the die line. The pre-fix behaviour was to
        return from the handler normally and let the workflow
        succeed — which masked destructive partial state
        (e.g. ``/squash`` with a successful ``git reset --soft`` +
        ``git commit`` but a rejected ``git push``: the local
        branch is squashed, the remote is not, the next push is a
        force-push onto a divergence the user did not intend).

        The response is posted via
        ``post_pr_comment_attributed`` so the comment
        thread carries an ``@<commenter>,`` prefix —
        the worker runs in response to a single
        comment event per workflow, and
        ``payload.sender.login`` is the user who
        posted the slash command. Non-slash-command PR
        comments (e.g. ``_pr_review``'s follow-up
        summary) keep the plain ``post_pr_comment`` so
        the bot's review summary is not misattributed to
        whichever user last commented.
        """
        result = self.gitea.post_pr_comment_attributed(
            pr_repo, pr_number, body)
        if result is None:
            log(f"slash-command: WARNING failed to post response "
                f"comment to {pr_repo}#{pr_number}",
                file=sys.stderr)
        if fatal:
            label = f"/{command}" if command else "(unknown)"
            die(f"slash-command: {label} failed: workflow halted after "
                f"posted failure response")
        return result

    def _slash_help(self, pr_repo, pr_number, pr_url):
        """``/help`` — list supported slash commands as a PR comment."""
        lines = ["**Supported slash commands:**", ""]
        for cmd, desc in self.SUPPORTED_COMMANDS:
            lines.append(f"- `/{cmd}` — {desc}")
        self._post_slash_response(pr_repo, pr_number, "\n".join(lines))

    def _slash_do(self, pr_repo, pr_number, pr_url,
                  thread_path=None, thread_line=None):
        """``/do`` — execute the instructions in the
        inline-review-comment conversation the user
        replied to.

        ``/do`` is REPLY-ONLY on a Gitea "conversation".
        Gitea's "conversation" data structure is
        defined exclusively for inline review comments
        (``CommentTypeCode``), grouped by
        ``(path, line)`` — see
        ``models/issues/comment_code.go:22`` and
        ``models/issues/review.go:935`` (the
        ``MarkConversation`` function explicitly
        checks ``comment.Type != CommentTypeCode``
        and returns early for anything else).
        Issue comments on a PR are rendered as a flat
        chronological list with NO parent-of-reply
        relationship in Gitea's data model, so they
        have no "conversation" to target. The
        ``if thread cannot be identified do nothing``
        rule is therefore load-bearing for the
        issue-comment case: the thread cannot be
        identified (Gitea has no concept of an issue
        comment thread), so the handler does nothing.

        The dispatcher reads the webhook payload's
        ``comment.path`` and ``comment.position``
        fields. These are present only when the
        triggering comment is a reply to an inline
        review comment — i.e. it was posted via the
        code-comment "Reply" form in the conversation
        view. Top-level issue comments (and replies
        to them, which are also top-level issue
        comments) have no ``path``/``position``;
        ``/do`` posted there is dropped on the floor
        with a log line and no response comment
        (the gate is silent, matching the
        pre-existing trust-gate pattern).

        Once the ``(path, line)`` anchor is
        recovered, the workflow asks Gitea for JUST
        that conversation via
        ``get_pr_review_thread`` (a single-
        conversation query — not a "list all +
        filter" roundtrip) and feeds the
        conversation's combined body to the agent as
        the prompt. The agent prompt is the comment
        body and ONLY the comment body — no PR URL,
        no PR number, no references to other
        comments, no instructions about MCP tools.
        The agent's working tree has the PR diff
        applied (set up elsewhere in the workflow)
        and the codebase is available via the
        agent's normal tools; the comment body is
        sufficient to identify what the user wants
        changed.

        One commit per ``/do`` invocation, covering
        whatever the agent changed. The
        conversation's root comment id is recorded
        in the commit body so the link back to the
        originating comment stays intact. The
        conversation is resolved only if the agent
        produced a non-empty commit (mirrors the
        ``_pr_comment`` discipline: failed/no-op
        runs leave the conversation unresolved for
        the next ``/do`` invocation).
        """
        # Conversation-identification gate. Gitea
        # defines a "conversation" only for inline
        # review comments (the ``(path, position)``
        # pair); issue comments are flat
        # chronological lists with no parent
        # relation, so they have no conversation
        # to address. A ``/do`` posted as a reply
        # to an issue comment (or as a top-level
        # issue comment) reaches here with
        # ``thread_path``/``thread_line`` set to
        # ``None`` (those fields are only on
        # review-comment replies), and the
        # handler silently returns.
        if thread_path is None or thread_line is None:
            log(f"slash-do: /do without identifiable thread "
                f"(thread_path={thread_path!r} "
                f"thread_line={thread_line!r}); ignoring")
            return

        log(f"slash-do: fetching conversation at "
            f"{thread_path}:{thread_line} for pr={pr_url}")
        thread = self.gitea.get_pr_review_thread(
            pr_repo, pr_number, thread_path, thread_line)
        if thread is None:
            # No unresolved comments at this anchor
            # (the conversation was the only one and
            # is now resolved, or the anchor doesn't
            # match any review comment). Tell the
            # user so they can pick a different
            # thread.
            self._post_slash_response(
                pr_repo, pr_number,
                f"`/do`: no unresolved review comments "
                f"found in the conversation at "
                f"`{thread_path}:{thread_line}`. "
                f"Nothing to execute.")
            return

        # The body is the conversation's combined
        # body: ``[login1]: body1\n\n[login2]: body2\n…``
        # All participants (slave, trusted humans,
        # replies via follow-up reviews) are
        # included. The agent sees exactly this
        # text — nothing else — so the prompt
        # cannot leak the rest of the PR.
        prompt = thread.get("body", "")
        thread_id = thread.get("id")

        self.agent.start_session("pr-do")
        deferred_resolves = []
        try:
            # ``resume=False`` (NOT ``True``): the session was
            # JUST minted by ``start_session("pr-do")`` a
            # microsecond ago, so qwen has no on-disk record
            # to look up under ``--resume``. ``Agent.prompt``
            # maps ``resume=False`` to ``--session-id <uuid>``,
            # which tells qwen to create a fresh on-disk
            # session under our chosen uuid (the only way to
            # establish the session in the first place).
            # ``resume=True`` here was a copy-paste residue from
            # ``_pr_comment`` — that handler chains several
            # prompts and needs ``--resume`` to keep them in
            # one conversation; ``_slash_do`` makes a single
            # prompt then ``stop_session``s immediately, so there
            # is no chain to rejoin. Passing ``resume=True``
            # against a brand-new session id surfaces as
            # ``qwen --resume`` failing with
            # "No saved session found with ID <uuid>",
            # ``qwen exited with code 1``, and the run dying
            # in ``die(f"qwen agent exited with code {rc}")``
            # below — even though the conversation was
            # correctly identified and the prompt body
            # faithfully built.
            rc = self.agent.prompt_with_retry(
                prompt,
                timeout=Agent.AGENT_TIMEOUT,
                retry_label="pr-do")
            if rc == 124:
                anchor = (f"{thread_path}:{thread_line}"
                          if thread_path and thread_line
                          else "")
                self._handle_timeout(
                    pr_repo, pr_number, pr_url, [],
                    caller="pr-do", context_label=anchor)
            if rc != 0:
                die(f"qwen agent exited with code {rc}")

            summary = self.agent.otlp.get_review_text().strip()
            # One commit per /do invocation. The
            # subject pins the command and the
            # conversation location; the body
            # carries the link back to the
            # originating review comment and
            # (optionally) the Argo run URL and
            # the agent's summary.
            commit_subject = (
                f"do: instruction(s) from PR comment conversation at "
                f"`{thread_path}:{thread_line}`"
            )
            comment_links = ""
            if thread_id is not None:
                comment_links = (
                    f"- {pr_url}#issuecomment-{thread_id}\n")
            run_url = params.shoggoth_argo_run_url
            run_url_line = (f"\nArgo run: {run_url}"
                             if run_url else "")
            summary_section = (
                f"\n\nAgent summary:\n\n{summary[:2000]}"
                if summary else ""
            )
            commit_msg = (
                f"{commit_subject}\n\n"
                f"{comment_links}{run_url_line}"
                f"{summary_section}"
            ).rstrip() + "\n"
            committed = self._commit_only(commit_msg)
            # Only resolve the conversation if a
            # non-empty commit actually landed. A
            # no-op agent run leaves the
            # conversation unresolved for the next
            # ``/do`` invocation — same discipline
            # as ``_pr_comment``.
            if committed and thread_id is not None:
                deferred_resolves.append(thread_id)
        finally:
            self._push_pending_commits()
            for comment_id in deferred_resolves:
                r = self.gitea.resolve_comment(pr_repo, comment_id)
                if r is None:
                    log(f"slash-do: WARNING resolve failed for "
                        f"comment {comment_id}")
            self.agent.stop_session()
        self._post_slash_response(
            pr_repo, pr_number,
            f"Executed `/do` for the conversation at "
            f"`{thread_path}:{thread_line}`.")

    def _slash_review(self, pr_repo, pr_number, pr_url):
        """``/review`` — request a review from the slave user.

        Identical to assigning a review request to ``slave_user`` via
        the Gitea UI: posts to
        ``/repos/{repo}/pulls/{n}/requested_reviewers`` which fires
        a ``pull_request_review_request`` webhook. The existing
        review handler in ``execute()`` picks that up and runs the
        normal review flow. Only the REVIEW RESULT is posted back
        to the PR — there is intentionally no "Review requested
        from ..." confirmation comment because that message would
        sit next to the actual review in the PR thread and add
        noise without information (the user already knows they
        asked for a review, and the Gitea UI shows the reviewer
        assignment in the sidebar).

        Failure modes that DO post:
          * ``request_reviewer`` returned ``None`` (Gitea
            rejected the add) — fatal comment, then ``die()`` so
            the workflow is marked Failed.
          * The slave user is the PR author — Gitea would 422
            the reviewer-add with ``poster of pr can't be
            reviewer``, so the webhook never fires and the
            review never runs. Detect this from the loaded
            webhook payload and run the review directly via
            ``_pr_review`` (no PR comment — the review itself
            posts the result).
        """
        slave_user = params.shoggoth_slave_user
        pr_poster = ((self.gitea._payload.get("pull_request") or {})
                     .get("user") or {}).get("login") or ""
        if not pr_poster:
            # ``issue_comment`` webhooks on a PR also carry the PR
            # under ``issue``; fall back to that key.
            pr_poster = ((self.gitea._payload.get("issue") or {})
                         .get("user") or {}).get("login") or ""
        if slave_user and pr_poster and pr_poster == slave_user:
            log(f"slash-review: {slave_user} is the author of "
                f"{pr_repo}#{pr_number}; running review directly "
                f"instead of the request_reviewer webhook round-trip",
                file=sys.stderr)
            self._pr_review(pr_url)
            return
        log(f"slash-review: requesting review from {slave_user} "
            f"on {pr_repo}#{pr_number}")
        result = self.gitea.request_reviewer(pr_repo, pr_number, slave_user)
        if result is None:
            log(f"slash-review: request_reviewer returned None",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to request review from `{slave_user}`.",
                fatal=True, command="review")
            return
        # No success comment posted: the
        # ``pull_request_review_request`` webhook fires
        # next, the existing review handler runs, and
        # that handler's output IS the result the user
        # sees in the PR thread. A "Review requested
        # from ..." comment here would be redundant
        # noise between the user's ``/review`` command
        # and the review itself.

    def _slash_squash(self, pr_repo, pr_number, pr_url):
        """``/squash`` — squash all PR commits into one.

        Two-stage flow: (1) an agent generates a commit message from
        the cumulative diff (subject + Markdown body), (2) a soft
        ``git reset`` to the merge-base with the target branch
        followed by a single ``git commit`` with the generated
        message. The squashed branch is then force-pushed.

        ccws note: this operates on the manifest repo (the one
        holding the working branch). Sub-repos keep their per-PR
        commit history; a full cross-repo squash would require a
        separate per-sub-repo reset+recommit loop that this handler
        does not implement. For standalone repos the manifest is
        the only repo and the squash is exact.
        """
        repo_dir = self.shoggoth.repo_dir
        pr_branch = self.shoggoth.working_branch
        pr_data = self.gitea.get_pr(pr_repo, pr_number)
        if not pr_data:
            log(f"slash-squash: get_pr returned no data",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to get PR #{pr_number} info.",
                fatal=True, command="squash")
            return
        base_ref = (pr_data.get("base") or {}).get("ref", "")
        if not base_ref:
            log(f"slash-squash: no base ref in PR data",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                "Failed to determine base branch.",
                fatal=True, command="squash")
            return

        log(f"slash-squash: base={base_ref} branch={pr_branch} "
            f"repo={repo_dir}")
        self.shoggoth._unshallow(repo_dir)
        self.shoggoth._ensure_remote_ref(repo_dir, base_ref, pr_number)
        base_sha = self._resolve_remote_ref(repo_dir, f"origin/{base_ref}")
        if not base_sha:
            log(f"slash-squash: failed to resolve origin/{base_ref}",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to resolve base ref `{base_ref}`.",
                fatal=True, command="squash")
            return

        diff_text = self._pr_diff_for_prompt(repo_dir, pr_repo,
                                              pr_number, base_ref)
        if not diff_text:
            self._post_slash_response(pr_repo, pr_number,
                "Failed to compute PR diff for squash.",
                fatal=True, command="squash")
            return
        if len(diff_text) > 80000:
            diff_text = diff_text[:80000] + "\n... (truncated)"

        commit_msg = self._agent_generate_squash_message(
            pr_url, pr_repo, pr_number, pr_branch, base_ref,
            diff_text, repo_dir)
        if commit_msg is None:
            return  # _agent_generate_squash_message already posted failure (fatal)

        # Pre-flight: verify the push would succeed before doing any
        # destructive local work (``git reset --soft`` + ``git
        # commit``). If the server would reject the push, bail out
        # with the local branch in its pre-squash state so the user
        # can fix the permission and retry.
        if not self._preflight_push(pr_repo, pr_number, pr_branch,
                                     repo_dir, "squash"):
            return  # _preflight_push already posted a fatal failure

        g = Git(repo_dir)
        reset = g.reset_soft(base_sha, check=False)
        if reset.returncode != 0:
            log(f"slash-squash: git reset --soft failed: "
                f"{reset.stderr.strip()[:200]}", file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to soft reset to base: "
                f"{reset.stderr.strip()[:200]}",
                fatal=True, command="squash")
            return

        cached = g.diff_cached_name_only(check=False)
        if not cached.stdout.strip():
            log(f"slash-squash: nothing staged after reset "
                f"(branch already at base)")
            self._post_slash_response(pr_repo, pr_number,
                "No changes to squash (branch already at base).")
            return

        commit = g.commit(commit_msg, check=False)
        if commit.returncode != 0:
            log(f"slash-squash: git commit failed: "
                f"{commit.stderr.strip()[:200]}", file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to commit squashed changes: "
                f"{commit.stderr.strip()[:200]}",
                fatal=True, command="squash")
            return

        push = g.push("origin", pr_branch, force_with_lease=True,
                       check=False)
        if push.returncode != 0:
            stderr = (push.stderr or "").strip()[:500]
            log(f"slash-squash: git push failed: {stderr}",
                file=sys.stderr)
            self._post_slash_response(
                pr_repo, pr_number,
                f"Failed to push squashed branch — the local "
                f"branch is squashed (one commit on top of the "
                f"base) but the remote is unchanged. Server said:"
                f"\n\n```\n{stderr}\n```\n\n"
                f"To finish the squash, push from a machine that "
                f"has push access to `{pr_branch}`:\n\n"
                f"```\n"
                f"git fetch origin\n"
                f"git checkout {pr_branch}\n"
                f"git push --force-with-lease origin {pr_branch}\n"
                f"```\n\n"
                f"Or grant the shoggoth slave write permission on "
                f"this repo and retry — the pre-flight check "
                f"would then catch it before any destructive local "
                f"op runs.",
                fatal=True, command="squash")
            return

        log(f"slash-squash: successfully squashed {pr_branch}")
        self._post_slash_response(pr_repo, pr_number,
            f"Branch `{pr_branch}` squashed into a single commit "
            f"and force-pushed.")

    def _agent_generate_squash_message(self, pr_url, pr_repo, pr_number,
                                        pr_branch, base_ref, diff_text,
                                        repo_dir):
        """Invoke the agent to produce a squash commit message.

        Returns the commit message string (subject + body, separated
        by a blank line) on success, or ``None`` if the agent
        failed — in which case a failure response has already been
        posted via ``_post_slash_response``.

        ``tool_profile`` defaults to ``"full"`` (the agent is free
        to inspect the workspace for context); ``cwd`` is the repo
        directory so file references in the prompt resolve to the
        PR branch's checkout.
        """
        self.agent.start_session("pr-squash")
        try:
            prompt = (
                f"Generate a git commit message for squashing all "
                f"commits in PR {pr_url} (repo `{pr_repo}`, "
                f"PR #{pr_number}, branch `{pr_branch}`, target "
                f"`{base_ref}`).\n\n"
                f"The cumulative diff is:\n\n```diff\n{diff_text}\n```\n\n"
                f"Output a JSON object in a ```json fenced block, "
                f"followed by the literal line END_OF_SQUASH on its "
                f"own line. The JSON shape is:\n"
                f"```\n"
                f"{{\n"
                f'  "subject": "concise subject line (50-72 chars, '
                f'imperative mood, no trailing period)",\n'
                f'  "body": "summary of the change in under 10 '
                f'lines (Markdown allowed; wrap at 72 chars; no '
                f'bullet padding, no preambles, no "this commit" '
                f'phrasing)"\n'
                f"}}\n"
                f"```\n"
            )
            rc = self.agent.prompt_with_retry(
                prompt, timeout=Agent.AGENT_TIMEOUT,
                cwd=repo_dir, retry_label="pr-squash")
            if rc != 0:
                log(f"slash-squash: agent rc={rc}", file=sys.stderr)
                self._post_slash_response(pr_repo, pr_number,
                    f"Failed to generate squash commit message "
                    f"(agent rc={rc}).",
                    fatal=True, command="squash")
                return None
            response_text = self.agent.otlp.get_review_text()
            data = self.agent._extract_agent_json(response_text,
                                                   "END_OF_SQUASH",
                                                   ("subject", "body"))
            if not data:
                log(f"slash-squash: failed to extract JSON from agent "
                    f"output (length={len(response_text) if response_text else 0})",
                    file=sys.stderr)
                self._post_slash_response(pr_repo, pr_number,
                    "Failed to parse squash commit message from agent.",
                    fatal=True, command="squash")
                return None
            subject = (data.get("subject") or "").strip()
            body = (data.get("body") or "").strip()
            if not subject:
                log(f"slash-squash: agent returned empty subject",
                    file=sys.stderr)
                self._post_slash_response(pr_repo, pr_number,
                    "Agent generated an empty squash commit subject.",
                    fatal=True, command="squash")
                return None
            return f"{subject}\n\n{body}" if body else subject
        finally:
            self.agent.stop_session()

    def _slash_rebase(self, pr_repo, pr_number, pr_url):
        """``/rebase`` — rebase the PR branch on top of the target.

        Two-stage flow: (1) ``git fetch origin <base>`` + ``git
        rebase origin/<base>`` with ``GIT_EDITOR=true`` so the
        rebase does not hang waiting for a commit-message editor,
        (2) on conflict, the agent reads the conflicted files and
        produces resolved content as JSON; the workflow writes it
        back, ``git add``s each file, and continues the rebase in a
        loop until done.

        Conflict resolution is bounded by ``_resolve_rebase_conflicts``
        (max steps); if the agent fails to resolve cleanly the
        rebase is aborted and a failure comment posted. The
        rebased branch is force-pushed on success.

        ccws note: same caveat as ``_slash_squash`` — the manifest
        is rebased; sub-repo branches are not.
        """
        repo_dir = self.shoggoth.repo_dir
        pr_branch = self.shoggoth.working_branch
        pr_data = self.gitea.get_pr(pr_repo, pr_number)
        if not pr_data:
            log(f"slash-rebase: get_pr returned no data",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to get PR #{pr_number} info.",
                fatal=True, command="rebase")
            return
        base_ref = (pr_data.get("base") or {}).get("ref", "")
        if not base_ref:
            log(f"slash-rebase: no base ref in PR data",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                "Failed to determine base branch.",
                fatal=True, command="rebase")
            return

        log(f"slash-rebase: base={base_ref} branch={pr_branch}")
        self.shoggoth._unshallow(repo_dir)
        self.shoggoth._ensure_remote_ref(repo_dir, base_ref, pr_number)

        g = Git(repo_dir)
        fetch = g.fetch(remote="origin", ref=base_ref, check=False)
        if fetch.returncode != 0:
            log(f"slash-rebase: fetch failed: "
                f"{fetch.stderr.strip()[:200]}", file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                f"Failed to fetch base branch: "
                f"{fetch.stderr.strip()[:200]}",
                fatal=True, command="rebase")
            return

        # GIT_EDITOR=true prevents the rebase / rebase --continue
        # from hanging on a commit-message prompt. The default
        # commit message (whatever was on the rebased commit) is
        # accepted as-is for resolution-loop continues.
        rebase_env = {**os.environ, "GIT_EDITOR": "true",
                      "GIT_SEQUENCE_EDITOR": "true"}

        # Pre-flight: verify the push would succeed before doing
        # the destructive ``git rebase``. A successful rebase
        # whose push is rejected leaves the local branch in a
        # state the remote cannot absorb (the user's other
        # machines cannot force-push the same divergence back).
        if not self._preflight_push(pr_repo, pr_number, pr_branch,
                                     repo_dir, "rebase"):
            return  # _preflight_push already posted a fatal failure

        rebase = g.rebase(f"origin/{base_ref}", env=rebase_env,
                          check=False)
        if rebase.returncode == 0:
            self._push_force(pr_repo, pr_number, pr_branch, repo_dir,
                              f"Branch `{pr_branch}` rebased onto "
                              f"`{base_ref}` and force-pushed.",
                              command="rebase")
            return

        log(f"slash-rebase: rebase encountered conflicts, invoking "
            f"agent")
        resolved = self._resolve_rebase_conflicts(
            repo_dir, pr_repo, pr_number, pr_url, base_ref, rebase_env)
        if not resolved:
            g.rebase_abort(env=rebase_env, check=False)
            log(f"slash-rebase: conflict resolution failed; aborted",
                file=sys.stderr)
            self._post_slash_response(pr_repo, pr_number,
                "Could not automatically resolve rebase conflicts. "
                "Manual intervention required.",
                fatal=True, command="rebase")
            return

        self._push_force(pr_repo, pr_number, pr_branch, repo_dir,
                          f"Branch `{pr_branch}` rebased onto "
                          f"`{base_ref}` (conflicts resolved by agent) "
                          f"and force-pushed.",
                          command="rebase")

    def _push_force(self, pr_repo, pr_number, pr_branch, repo_dir,
                     success_msg, command="rebase"):
        """Force-push ``pr_branch`` from ``repo_dir``; post
        ``success_msg`` on success or an error comment on failure.

        ``--force-with-lease`` (not ``--force``) refuses the push
        when the upstream branch has moved since the last fetch —
        matching the existing ``_commit_only``+``_push_pending_commits``
        philosophy of safe force-pushes for the workflow script.
        """
        push = Git(repo_dir).push("origin", pr_branch,
                                   force_with_lease=True, check=False)
        if push.returncode != 0:
            stderr = (push.stderr or "").strip()[:500]
            log(f"slash-{command}: push failed: {stderr}",
                file=sys.stderr)
            self._post_slash_response(
                pr_repo, pr_number,
                f"Failed to push rebased branch — the local "
                f"branch is rebased (in front of the target) but "
                f"the remote is unchanged. Server said:\n\n"
                f"```\n{stderr}\n```\n\n"
                f"To finish the rebase, push from a machine that "
                f"has push access to `{pr_branch}`:\n\n"
                f"```\n"
                f"git fetch origin\n"
                f"git checkout {pr_branch}\n"
                f"git push --force-with-lease origin {pr_branch}\n"
                f"```\n\n"
                f"Or grant the shoggoth slave write permission on "
                f"this repo and retry — the pre-flight check "
                f"would then catch it before any destructive local "
                f"op runs.",
                fatal=True, command=command)
            return False
        log(f"slash-{command}: force-push of {pr_branch} OK")
        self._post_slash_response(pr_repo, pr_number, success_msg)
        return True

    def _preflight_push(self, pr_repo, pr_number, pr_branch, repo_dir,
                        command):
        """Verify the push would succeed before any destructive local
        op. Two layered checks:

        1. ``Gitea.can_push`` — a Gitea-API call to read the
           authenticated user's ``permissions.push`` on the repo.
           The most reliable signal for the "User permission
           denied for writing" case (a server-side ACL the
           receiving end runs on every push before any hook
           fires). Returns ``False`` on a clean "no" and
           ``None`` on a lookup failure — the second is treated
           as fail-closed.

        2. ``git push --dry-run --force-with-lease`` against the
           actual remote. Catches network errors, missing remote
           refs, and any ACL/branch-protection check the server
           runs on dry-runs.

        On either failure, posts a fatal slash response and dies.
        The caller MUST NOT have run ``git reset --soft``,
        ``git commit`` or ``git rebase`` at this point — a
        destructive local state on a branch whose push the server
        rejects is what we are guarding against: the local branch
        diverges from the remote in a way no other machine can
        resolve without manual intervention. Failing here keeps
        the local branch in its pre-destructive state so the user
        can fix the permission/branch-protection and retry.

        The actual ``git push`` at the end of the handler is
        still the authoritative check — pre-receive hooks do not
        fire on dry-runs (verified empirically), and a hook
        verdict that depends on server state not visible to the
        client will only surface there. The preflight is a
        fast-fail, not a guarantee.
        """
        # Check 1: Gitea API permission (most reliable for the
        # ACL case the user reported).
        can_push = self.gitea.can_push(pr_repo)
        if can_push is False:
            log(f"slash-{command}: preflight denied by Gitea API "
                f"(no push permission on {pr_repo})", file=sys.stderr)
            self._post_slash_response(
                pr_repo, pr_number,
                f"Push preflight failed — Gitea reports the "
                f"authenticated user does not have write permission "
                f"on `{pr_repo}`. Refusing to run destructive local "
                f"ops (``git reset --soft`` / ``git commit`` / "
                f"``git rebase``) on a branch that cannot be "
                f"pushed. Grant push access (or have someone with "
                f"push access run the command) and retry. The "
                f"local branch has not been modified.",
                fatal=True, command=command)
            return False
        if can_push is None:
            log(f"slash-{command}: preflight could not read "
                f"permissions from Gitea API; failing closed",
                file=sys.stderr)
            self._post_slash_response(
                pr_repo, pr_number,
                f"Push preflight failed — could not read the "
                f"authenticated user's permissions on `{pr_repo}` "
                f"from the Gitea API. Refusing to run destructive "
                f"local ops on a branch whose push state is "
                f"unknown. Retry once the API is reachable.",
                fatal=True, command=command)
            return False

        # Check 2: dry-run push (catches network / ref / branch-
        # protection cases the API check misses).
        g = Git(repo_dir)
        dry_run = g.push("origin", pr_branch, force_with_lease=True,
                          dry_run=True, check=False)
        if dry_run.returncode != 0:
            stderr = (dry_run.stderr or "").strip()[:500]
            log(f"slash-{command}: preflight push rejected: {stderr}",
                file=sys.stderr)
            self._post_slash_response(
                pr_repo, pr_number,
                f"Push preflight failed — the dry-run push was "
                f"rejected (the actual ``git push`` would be "
                f"rejected the same way, leaving the local branch "
                f"in a state the remote could not absorb). Server "
                f"said:\n\n"
                f"```\n{stderr}\n```\n\n"
                f"Fix the branch protection, pre-receive hook, or "
                f"transport issue and retry. The local branch has "
                f"not been modified.",
                fatal=True, command=command)
            return False
        log(f"slash-{command}: preflight OK (Gitea push perm + "
            f"dry-run push)")
        return True

    def _resolve_rebase_conflicts(self, repo_dir, pr_repo, pr_number,
                                   pr_url, base_ref, rebase_env):
        """Iteratively resolve rebase conflicts using the agent.

        Loop body: check whether the rebase is still active, then
        either ``git rebase --continue`` (when no unmerged files
        remain) or hand the unmerged files to the agent for
        resolution. Each loop iteration starts a fresh agent
        session so a single failed prompt cannot poison the rest
        of the resolution; the cost is the plugin-download /
        codebase-index overhead on each iteration, accepted in
        exchange for fault isolation.

        Returns ``True`` when the rebase completes (the agent has
        resolved every conflict), ``False`` on any unrecoverable
        failure (the caller aborts the rebase and posts an error
        comment).
        """
        g = Git(repo_dir)
        max_steps = 20
        for step in range(max_steps):
            in_progress = self._rebase_in_progress(repo_dir)
            if not in_progress:
                log(f"slash-rebase: rebase complete after {step} step(s)")
                return True

            unmerged = g.diff_name_only_filter("U", check=False)
            conflicted = [f for f in unmerged.stdout.strip().splitlines()
                          if f]

            if not conflicted:
                cont = g.rebase_continue(env=rebase_env, check=False)
                if cont.returncode == 0:
                    continue
                stderr = (cont.stderr or "").lower()
                if "no changes" in stderr:
                    skip = g.rebase_skip(env=rebase_env, check=False)
                    if skip.returncode != 0:
                        log(f"slash-rebase: rebase --skip failed: "
                            f"{(skip.stderr or '').strip()[:200]}",
                            file=sys.stderr)
                        return False
                    continue
                log(f"slash-rebase: rebase --continue failed: "
                    f"{(cont.stderr or '').strip()[:200]}",
                    file=sys.stderr)
                return False

            ok = self._resolve_file_conflicts_with_agent(
                repo_dir, conflicted, pr_url, repo_dir)
            if not ok:
                return False

        log(f"slash-rebase: hit max steps ({max_steps}), giving up",
            file=sys.stderr)
        return False

    @staticmethod
    def _rebase_in_progress(repo_dir):
        """Return True if ``repo_dir`` is in the middle of a rebase.

        Both ``git-rebase`` (``rebase-merge/``) and ``git-rebase
        --interactive``/``--apply`` (``rebase-apply/``) leave a
        marker under the git dir; checking both keeps the helper
        robust against the rebase backend ``git`` chose.

        ``git rev-parse --git-path <marker>`` is a path *resolver* —
        it always succeeds and prints the resolved path string
        regardless of whether the marker actually exists on disk —
        so we also ``os.path.exists`` the resolved path before
        claiming a rebase is in progress.
        """
        g = Git(repo_dir)
        for marker in ("rebase-merge", "rebase-apply"):
            probe = g.rev_parse_git_path(marker, check=False)
            if (probe.returncode == 0
                    and probe.stdout.strip()
                    and os.path.exists(probe.stdout.strip())):
                return True
        return False

    def _resolve_file_conflicts_with_agent(self, repo_dir, conflicted,
                                            pr_url, agent_cwd):
        """Use the agent to resolve one batch of conflicted files.

        Reads each conflicted file (with conflict markers intact),
        hands the contents to the agent as a JSON payload, and
        asks for ``{"resolutions": [{"path": ..., "content": ...}]}``.
        Resolved contents are written back and ``git add``ed; a
        failure (missing path in the agent's response, read/write
        error, agent rc != 0) returns False so the rebase can be
        aborted cleanly.

        One agent session per batch: cheaper ``start_session`` cost
        is acceptable in exchange for the per-batch fault
        isolation the ``_resolve_rebase_conflicts`` loop relies on.
        """
        file_contents = {}
        for filepath in conflicted:
            full_path = os.path.join(repo_dir, filepath)
            try:
                with open(full_path) as f:
                    file_contents[filepath] = f.read()
            except OSError as e:
                log(f"slash-rebase: cannot read conflicted file "
                    f"{filepath}: {e}", file=sys.stderr)
                return False

        try:
            files_payload = json.dumps(file_contents, indent=2)
        except (TypeError, ValueError) as e:
            log(f"slash-rebase: cannot serialise file contents: {e}",
                file=sys.stderr)
            return False
        if len(files_payload) > 150000:
            log(f"slash-rebase: conflicted files payload too large "
                f"({len(files_payload)} chars), truncating", file=sys.stderr)
            files_payload = files_payload[:150000] + "\n... (truncated)"

        self.agent.start_session("pr-rebase")
        try:
            prompt = (
                f"Resolve git rebase conflicts in PR {pr_url}.\n\n"
                f"The following files have unresolved conflicts "
                f"(<<<<<<<, =======, >>>>>>> markers):\n\n"
                + "\n".join(f"- `{p}`" for p in conflicted) +
                "\n\nFor each file, understand the changes from both "
                f"branches and produce a clean version with all "
                f"conflict markers removed. Do not add new features or "
                f"refactor; only resolve the conflicts.\n\n"
                f"File contents (JSON-encoded, paths are relative to "
                f"the repo root):\n\n"
                f"```json\n{files_payload}\n```\n\n"
                f"Output a JSON object in a ```json fenced block, "
                f"followed by the literal line END_OF_REBASE on its "
                f"own line. The JSON shape is:\n"
                f"```\n"
                f"{{\n"
                f'  "resolutions": [\n'
                f"    {{\n"
                f'      "path": "relative/path/to/file",\n'
                f'      "content": "resolved file content as a string"\n'
                f"    }}\n"
                f"  ]\n"
                f"}}\n"
                f"```\n"
            )
            rc = self.agent.prompt_with_retry(
                prompt, timeout=Agent.AGENT_TIMEOUT,
                cwd=agent_cwd, retry_label="pr-rebase")
            if rc != 0:
                log(f"slash-rebase: agent rc={rc}", file=sys.stderr)
                return False
            response_text = self.agent.otlp.get_review_text()
            data = self.agent._extract_agent_json(response_text,
                                                   "END_OF_REBASE",
                                                   ("resolutions",))
            if not data or "resolutions" not in data:
                log(f"slash-rebase: failed to extract resolutions JSON",
                    file=sys.stderr)
                return False
            resolutions = data.get("resolutions") or []
        finally:
            self.agent.stop_session()

        by_path = {r.get("path"): r.get("content")
                   for r in resolutions
                   if isinstance(r, dict) and r.get("path") is not None}
        ok = True
        for filepath in conflicted:
            resolved_content = by_path.get(filepath)
            if resolved_content is None:
                log(f"slash-rebase: agent did not provide resolution "
                    f"for {filepath}", file=sys.stderr)
                ok = False
                continue
            full_path = os.path.join(repo_dir, filepath)
            try:
                with open(full_path, "w") as f:
                    f.write(resolved_content)
            except OSError as e:
                log(f"slash-rebase: cannot write resolved file "
                    f"{filepath}: {e}", file=sys.stderr)
                ok = False
                continue
            add = Git(repo_dir).add(filepath, check=False)
            if add.returncode != 0:
                log(f"slash-rebase: git add {filepath} failed: "
                    f"{add.stderr.strip()[:200]}", file=sys.stderr)
                ok = False
        return ok

    @staticmethod
    def _resolve_remote_ref(repo_dir, ref):
        """Resolve ``ref`` (e.g. ``origin/main``) to its SHA. ``None``
        on failure.

        Used by ``_slash_squash`` to turn the PR's base branch into
        the SHA for ``git reset --soft <base_sha>``. ``rev-parse
        --verify`` fails loudly on missing refs, so a non-zero
        rc is the right "not found" signal.
        """
        rev = Git(repo_dir).rev_parse_verify(ref, check=False)
        if rev.returncode == 0 and rev.stdout.strip():
            return rev.stdout.strip()
        return None

    def _pr_diff_for_prompt(self, repo_dir, pr_repo, pr_number, base_ref):
        """Return the cumulative PR diff as text, or ``None`` on failure.

        Reuses the existing ``_write_pr_diff`` + Gitea ``.diff``
        fallback chain from the review path so the slash-command
        flows do not reinvent diff-fetching logic. The diff is the
        full ``base...head`` patch; callers trim it for prompt size
        if needed.
        """
        diff_path = (f"/tmp/shoggoth-squash-{pr_number}-"
                     f"{uuid.uuid4().hex[:8]}.diff")
        wrote = self.shoggoth._write_pr_diff(repo_dir, base_ref,
                                              None, diff_path)
        diff_text = ""
        if wrote and os.path.exists(diff_path):
            with open(diff_path) as f:
                diff_text = f.read()
        if not diff_text:
            gitea_diff = self.gitea.get_pr_diff_text(pr_repo, pr_number)
            if gitea_diff:
                diff_text = gitea_diff
        return diff_text or None

    def _handle_timeout(self, pr_repo, pr_number, pr_url,
                        resolved_comments, *, caller="pr-comment",
                        context_label=""):
        """Post a timeout message and ``die()``.

        ``resolved_comments`` is the per-comment progress
        the caller has accumulated before the timeout
        (``_pr_comment`` populates this with each comment
        addressed; ``_slash_do`` passes an empty list).

        ``caller`` selects the message wording:
          - ``"pr-comment"`` (default) — the per-comment
            framing ("Addressed N comment(s) before
            timeout").
          - ``"pr-do"`` — the per-conversation framing
            ("timed out on /do for the conversation at
            path:line; the conversation was left unresolved
            for the next /do").
        ``context_label`` is the anchor / context the
        caller attaches (a path:line for ``/do``; empty
        string for ``_pr_comment``). Kept separate from
        ``caller`` so the wording can be reused with a
        different anchor shape if a future caller adds one.

        ``die()`` fires after the body is posted, so the
        wording in the final line of ``timeout_msg`` is
        the last thing the workflow template surfaces —
        it must be accurate for both call sites.
        """
        log(f"{caller}: handling timeout"
            f"{(' resolved so far=' + str(len(resolved_comments))) if resolved_comments else ''}")
        self.agent.stop_session()
        resolved_count = len(resolved_comments) if resolved_comments else 0
        run_url = params.shoggoth_argo_run_url
        run_url_suffix = f" Argo run: {run_url}." if run_url else ""
        self._push_pending_commits()
        if caller == "pr-do":
            anchor_part = (f" for the conversation at {context_label}"
                           if context_label else "")
            timeout_msg = (
                f"Agent timed out after {Agent.AGENT_TIMEOUT // 60} minutes"
                f"{anchor_part}. No commits were produced and "
                f"the conversation was left unresolved for the next "
                f"/do invocation."
                f"{run_url_suffix}"
            )
        else:
            timeout_msg = (
                f"Agent timed out after {Agent.AGENT_TIMEOUT // 60} minutes. "
                f"Addressed {resolved_count} comment(s) before timeout. "
                f"Committed changes have been pushed."
                f"{run_url_suffix}"
            )
        self.gitea.post_pr_review_chunked(pr_repo, pr_number, timeout_msg)
        die(timeout_msg)
